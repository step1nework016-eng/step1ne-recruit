def build_message(item, idx, total):
    return (
        f"📞 <b>電訪清單 {idx}/{total}</b>\n"
        f"🏢 <b>{tg_bd._esc(item['company'])}</b>\n"
        f"☎️ {tg_bd._esc(item['phone'])}\n"
        f"👤 找誰：{tg_bd._esc(item['contact'])}\n"
        f"🎯 缺什麼：{tg_bd._esc(item['roles'])}\n"
        f"📝 {tg_bd._esc(item['note'])}\n"
        f"────────────\n"
        f"<b>30 秒開場白</b>\n{tg_bd._esc(item['script'])}\n"
        f"────────────\n"
        f"打完麻煩回覆這則：有興趣／沒興趣／給了信箱（信箱是多少）"
    )


def main(dry_run=False):
    head = (
        f"📋 <b>客戶開發｜電訪清單</b>（2026-09-24）\n"
        f"以下 {len(CALLS)} 家查不到可用的招募信箱，改請 Phoebe 電訪。\n"
        f"每家一則，麻煩打完回覆在該則下面即可。"
    )
    if SKIPPED:
        skip_lines = '\n'.join(f"• {s['company']}：{s['reason']}" for s in SKIPPED)
        head += f"\n\n⚠️ 先不排入這批（查無電話）：\n{skip_lines}"

    if dry_run:
        print(head)
        print('=' * 40)
        for i, item in enumerate(CALLS, 1):
            print(build_message(item, i, len(CALLS)))
            print('=' * 40)
        return

    tg_bd.send_head(head)
    for i, item in enumerate(CALLS, 1):
        tg_bd._post('sendMessage', {
            'text': build_message(item, i, len(CALLS)),
            'parse_mode': 'HTML',
            'disable_web_page_preview': True,
        })


if __name__ == '__main__':
    main(dry_run='--dry-run' in sys.argv)
