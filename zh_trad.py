_LOG = log


def to_traditional(text, logger=None):
    """草稿裡的簡體字轉成繁體。回傳轉好的文字；有轉到就記 log。"""
    if not text:
        return text
    table = dict(_S2T)
    if not _JA_HINT.search(text):
        table.update(_S2T_JA)
    hits = sorted({c for c in text if c in table})
    if not hits:
        return text
    (logger or _LOG)(f'✏️ 有簡體字，已自動轉繁體：{"、".join(c + "→" + table[c] for c in hits)}')
    return ''.join(table.get(c, c) for c in text)


